import http from 'k6/http';
import { check, sleep } from 'k6';
import { Counter } from 'k6/metrics';

const BASE = __ENV.API_URL || 'http://api-server:5000';
const INTERNAL_KEY = __ENV.INTERNAL_API_KEY || 'changeme';

const errors = new Counter('mixed_errors');
const writes = new Counter('write_count');

const relations = encodeURIComponent(
  JSON.stringify([{ name: 'tags' }, { name: 'category' }])
);

export const options = {
  vus: 20,
  duration: '60s',
  thresholds: {
    http_req_failed: ['rate<0.05'],
    http_req_duration: ['p(95)<500'],
  },
};

export default function () {
  const roll = Math.random();

  if (roll < 0.6) {
    // Light: simple list, no relations (60%)
    const limit = Math.floor(Math.random() * 20) + 5;
    const res = http.get(`${BASE}/posts/find?limit=${limit}`);
    check(res, { 'light 200': (r) => r.status === 200 });
    sleep(0.1);

  } else if (roll < 0.85) {
    // Medium: list with relations (25%)
    const limit = Math.floor(Math.random() * 20) + 10;
    const res = http.get(`${BASE}/posts/find?limit=${limit}&relations=${relations}`);
    check(res, { 'medium 200': (r) => r.status === 200 });
    sleep(0.2);

  } else if (roll < 0.95) {
    // Heavy: filtered + relations + order (10%)
    const where = encodeURIComponent(JSON.stringify({ isPublished: 1 }));
    const res = http.get(
      `${BASE}/posts/find?limit=50&relations=${relations}&where=${where}&order=${encodeURIComponent('{"createdAt":"DESC"}')}`
    );
    check(res, { 'heavy 200': (r) => r.status === 200 });
    sleep(0.3);

  } else {
    // Write: create a post (5%) — requires auth, will likely 401
    const payload = JSON.stringify({
      create: {
        title: `k6 Test Post ${Date.now()}`,
        content: 'Generated by k6 load test',
        isPublished: true,
      },
    });
    const res = http.post(`${BASE}/posts/create`, payload, {
      headers: { 'Content-Type': 'application/json' },
    });
    writes.add(1);
    // Expect 401 without auth — that's fine, we're measuring the framework overhead
    check(res, { 'write responded': (r) => r.status === 401 || r.status === 201 });
    sleep(0.5);
  }
}
